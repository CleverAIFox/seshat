"""**무엇이 같아야 견줄 수 있나** — 한 곳에서 답한다(DECISIONS §157).

  from seshat import compare
  compare.갈림(a_head, b_head, compare.AA)      # 같은 팔 두 판(A/A)
  compare.갈림(a_head, b_head, compare.AB)      # 처치 대 대조(A/B)
  compare.가린_지표(rec, target)                # 보호가 다르면 못 견주는 지표

★ **2026-09-28 하루에 같은 병을 여덟 번 앓았다** — 허용치(§139) · 이름(§143) · 반올림(§144) ·
  자(§145) · 올리기(§146) · 선 줄(§147) · 보호(§156) · 그리고 `compare_runs` 가 자를 안 보던 것.
  **전부 「견줄 수 없는 두 수를 견줬다」 의 변형**이고, 까닭은 하나다 — **조건이 다섯 곳에 손으로
  적혀 있었다**(문의 `check` 에 셋 · 문의 선 줄 · `noise.SAME` · `compare_runs`). 손으로 적으면
  반드시 한 곳이 빠진다.
★ **이 파일이 그 목록의 유일한 자리다.** 새 축이 생기면 여기에만 더한다.
★ **보호는 통째로 막지 않는다.** 보호가 다르면 **그 지표만** 못 견주고 나머지는 견준다 —
  `term_off` 는 끝까지 나온 문장을 재므로 양쪽 다 모델이 만든 값이다(§156).
★ **무엇을 지키는지는 팔이 안다** — `seshat/backends.py` 의 `보호` 표가 답한다(DECISIONS §186).
  2026-09-28 까지 기록판의 `protects` 칸에 **손으로** 적혀 있었고 거기 `keep` 이 빠져 있었다(§182).
"""
from __future__ import annotations

from typing import NamedTuple


class 축(NamedTuple):
    이름: str
    말머리: str        # 갈렸을 때 첫 줄. 문의 시험이 이 글자를 본다 — 바꾸면 같이 고친다
    왜: str


AXIS: dict[str, 축] = {
    "set_sha256": 축("셋", "셋이 다르다",
                     "다른 글로 잰 두 수를 견주면 그 비교가 거짓말이다(DECISIONS §45)"),
    "metrics": 축("자", "자가 바뀌었다",
                  "눈금이 달라졌다 — 같은 번역에 다른 수가 나온다(§145)"),
    "onto_sha256": 축("사전", "사전이 바뀌었다",
                      "같은 번역의 점수가 바뀐다(§32 · §96) — **분모가 바뀐다.** 2026-09-28 "
                      "`term_n` 674 → 982 에 **네 팔이 전부 내려갔다**(§166). **막지 않는다** — "
                      "막으면 사전을 영영 못 고친다. 재채점으로 기준을 다시 박으라고 이른다"),
    "backend": 축("팔", "팔이 다르다",
                  "다른 팔의 차이는 잡음이 아니다 — A/A 에서만 막는다"),
}

# 같은 팔을 여러 판(A/A) — 넷이 다 같아야 그 차이가 잡음이다
AA = ("backend", "set_sha256", "onto_sha256", "metrics")
# 처치 대 대조(A/B) — 팔은 다른 것이 요점이다
AB = ("set_sha256", "onto_sha256", "metrics")
# 문이 **막는** 축. 사전은 여기 없다 — 말만 한다
GATE_막 = ("metrics", "set_sha256")
# ★ **분모를 바꾸는 축**(DECISIONS §169). 이 셋 중 하나라도 갈리면 두 수는 **크기가 아니라 뜻이**
#   다르다 — 0.9532(982자리)와 0.9559(674자리)는 높낮이를 말할 수 없다. 그래서 **박으러 온 판에서는
#   견주지 않고 그대로 옮긴다.** 2026-09-28 `올릴_것` 은 이것을 알았고 `check` 는 몰라서, 문이 스스로
#   「자가 바뀌었다 · 사전이 바뀌었다」 를 찍은 **바로 다음 줄에서 그 수로 막았다.**
#   `set_sha256` 은 여기 없다 — **같은 시험지에서 분모만 바뀐 축**이 이 둘이고, 다른 시험지는
#   `GATE_막` 이 먼저 막는다. 선 줄은 셋 해시를 아예 안 들므로 넣으면 모든 선이 침묵한다
분모 = ("metrics", "onto_sha256")


class 갈린것(NamedTuple):
    키: str
    이름: str
    말머리: str
    왜: str
    가: object
    나: object

    def 글(self) -> str:
        return (f"{self.말머리} — 이쪽 {self.가 or '없다'} · 저쪽 {self.나 or '없다'}\n"
                f"    {self.왜}")


def 갈림(a: dict, b: dict, axes: tuple[str, ...]) -> list[갈린것]:
    """두 머리줄에서 **견줄 수 없게 만드는 축**만 든다. 비었으면 견줘도 된다.

    ★ **한쪽이 비어 있어도 갈린 것이다.** 「값이 없다」 는 「같다」 가 아니다 — 옛 판에는 `metrics`
      가 아예 없고, 그것을 같음으로 치면 자를 바꾸기 전후가 조용히 섞인다(§110 과 같은 규율).
    """
    out = []
    for k in axes:
        k = 사전축(a, b) if k == "onto_sha256" else k
        가, 나 = a.get(k), b.get(k)
        if (가 or "") != (나 or ""):
            축_ = AXIS[k]
            out.append(갈린것(k, 축_.이름, 축_.말머리, 축_.왜, 가, 나))
    return out


def 사전축(a: dict, b: dict) -> str:
    """**둘 다 들었으면 채점 지문으로, 아니면 바이트 해시로**(DECISIONS §171).

    ★ **옛 판과 안 갈라서려고 이렇게 한다.** 바이트 해시는 주석 · `src` · `ko_ref` 까지 해싱해서
      **뜻이 안 바뀐 편집이 견줄 수 있는 두 판을 막는다**(§169 의 거울상). 채점 지문은 채점기가
      읽는 칸만 본다. 옛 판에는 그 칸이 없으므로 **한쪽이라도 없으면 옛 자로 돌아간다** —
      「값이 없다」 를 「같다」 로 치는 것이 아니라 **옛 축으로 묻는 것**이다.
    ★ 옛 판끼리는 종전과 똑같이 굴고, 새 판끼리는 뜻이 안 바뀐 편집에 안 막힌다. **섞인 쌍만
      엄한 쪽(바이트)으로 간다** — 못 견주는 쪽으로 틀리는 것이 안전하다.
    """
    return "onto_score" if (a.get("onto_score") and b.get("onto_score")) else "onto_sha256"


def 같은_셋인가(가: dict, 나: dict) -> bool | None:
    """**둘이 같은 글을 쟀나.** None 은 「모른다」 — 견줄 이름이 한 쪽에도 없다(DECISIONS §173).

    ★ **해시가 먼저다.** 자리(`set`)는 옮기면 바뀌고 해시는 안 바뀐다. 둘 다 해시를 들면 해시로,
      아니면 자리로 묻는다 — 재채점 판은 `set_sha256` 만 들고 기록판의 선 줄은 `set` 만 든다.
    ★ **이 물음이 두 곳에 있었다.** 문의 `GATE_막` 이 해시로 묻고 선 박는 길이 자리로 물어서,
      재채점 판으로 선을 박으려다 「셋이 다르다 — 이번 None」 으로 막혔다(§169 와 같은 얼굴).
    """
    for k in ("set_sha256", "set"):
        if 가.get(k) and 나.get(k):
            return 가[k] == 나[k]
    return None


def 가린_지표(가: dict, 나: dict) -> set[str]:
    """보호가 달라서 **못 견주는 지표**. 통째로 막지 않는다(DECISIONS §156).

    ★ 자리표시가 지키는 `lit` 1.0 과 모델이 지킨 `lit` 0.92 는 **다른 수**다. 셋도 사전도 자도
      같으므로 위의 축들은 전부 통과한다 — 이것만이 그 차이를 본다.
    """
    from . import backends
    return set(backends.지키는_지표(_팔(가))) ^ set(backends.지키는_지표(_팔(나)))


def _팔(d: dict) -> str | None:
    """기록판 줄은 `arm`, 판 머리줄은 `backend` · `model` 로 팔을 든다."""
    return d.get("arm") or d.get("backend") or d.get("model")
